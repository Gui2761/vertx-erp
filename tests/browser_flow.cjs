/* Fluxo real em Chromium: geolocalização simulada, assinatura, limpeza, PDF e mobile. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'tmp', 'validation');
const fixture = JSON.parse(fs.readFileSync(path.join(output, 'browser.json'), 'utf8'));
const baseUrl = process.env.TEST_BASE_URL || fixture.base_url || 'http://127.0.0.1:8765';
if (process.env.TEST_LOCAL_TLS === 'True') assert.ok(['127.0.0.1', 'localhost'].includes(new URL(baseUrl).hostname), 'Ignorar certificado é permitido apenas no ensaio local.');
(async () => {
  const browser = await chromium.launch({headless: true, ...(process.env.BROWSER_EXECUTABLE ? {executablePath: process.env.BROWSER_EXECUTABLE} : {})});
  const context = await browser.newContext({ignoreHTTPSErrors: process.env.TEST_LOCAL_TLS === 'True', viewport: {width: 390, height: 844}, deviceScaleFactor: 1, isMobile: true, hasTouch: true, permissions: ['geolocation'], geolocation: {latitude: -9.665, longitude: -35.735, accuracy: 8}});
  if (fixture.cookie) await context.addCookies([{name: 'sessionid', value: fixture.cookie, domain: new URL(baseUrl).hostname, path: '/'}]);
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  if (fixture.username) {
    await page.goto(baseUrl + '/contas/login/');
    await page.locator('#id_username').fill(fixture.username);
    await page.locator('#id_password').fill(fixture.password);
    await page.getByRole('button', {name: 'Entrar', exact: true}).click();
    await page.waitForURL('**/vertyx/');
  } else await page.goto(baseUrl + '/vertyx/');
  if (baseUrl.startsWith('https://')) assert.equal(await page.evaluate(() => window.isSecureContext), true);
  assert.equal(await page.getByRole('heading', {name: 'VERTYX', exact: true}).count(), 1);
  assert.equal(await page.locator('#organization-select option:checked').textContent(), fixture.organization);
  await page.screenshot({path: path.join(output, 'vertyx-home-mobile.png'), fullPage: true});
  await page.getByRole('link', {name: 'Entrar no ERP Assistência'}).click();
  await page.waitForURL('**/assistencia/');
  await page.goto(`${baseUrl}/ordens/${fixture.ordem}/`);
  assert.equal(await page.getByRole('link', {name: 'Voltar para VERTYX', includeHidden: true}).count(), 1);
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).fontFamily.includes('system-ui')), true, 'Bootstrap local deve carregar');
  await page.getByRole('button', {name: 'Iniciar atendimento', exact: true}).click();
  await page.waitForURL(`**/ordens/${fixture.ordem}/`);
  await page.getByRole('link', {name: 'Editar atendimento'}).click();
  await page.locator('#id_diagnostico').fill('Fonte de alimentação defeituosa. Fusível e conexões avaliados.');
  await page.locator('#id_servico_executado').fill('Substituição da fonte, limpeza das conexões e ensaios funcionais. Equipamento entregue funcionando.');
  await page.locator('#id_pecas').fill('1 fonte de alimentação compatível');
  await page.getByRole('button', {name: 'Salvar', exact: true}).click();
  await page.locator('input[type=file]').setInputFiles(path.join(root, 'tests', 'photo_sample.png'));
  await page.locator('#id_descricao').fill('Fotografia de teste do equipamento');
  await page.getByRole('button', {name: 'Adicionar foto', exact: true}).click();
  assert.equal(await page.locator('.os-photo').count(), 1);
  // Exercise denied permission path on finalization, without fake coordinates.
  await page.evaluate(() => { navigator.geolocation.getCurrentPosition = (_success, error) => error({code: 1}); });
  await page.getByRole('button', {name: 'Conferir e finalizar atendimento'}).click();
  await page.getByRole('button', {name: 'Continuar com localização não obtida'}).waitFor({state: 'visible'});
  await page.getByRole('button', {name: 'Continuar com localização não obtida'}).click();
  await page.waitForURL('**/conferencia/**');
  await page.locator('#id_nome').fill('Maria Responsável de Teste');
  await page.locator('#id_cargo').fill('Gerente de manutenção');
  const canvas = page.locator('#signature-canvas');
  async function draw() {
    await canvas.scrollIntoViewIfNeeded();
    const box = await canvas.boundingBox();
    await page.mouse.move(box.x + 30, box.y + 80);
    await page.mouse.down();
    await page.mouse.move(box.x + 80, box.y + 25, {steps: 8});
    await page.mouse.move(box.x + 135, box.y + 135, {steps: 8});
    await page.mouse.move(box.x + 230, box.y + 90, {steps: 8});
    await page.mouse.up();
  }
  await draw();
  await page.getByRole('button', {name: 'Limpar assinatura'}).click();
  assert.equal(await page.locator('#id_imagem').inputValue(), '');
  assert.equal(await canvas.evaluate(c => {const data = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; return data.every(v => v === 255);}), true);
  await page.locator('#id_confirmacao').check();
  await page.getByRole('button', {name: 'Assinar e finalizar OS'}).click();
  assert.match(await page.locator('#signature-message').textContent(), /Desenhe/);
  await canvas.scrollIntoViewIfNeeded();
  const touchBox = await canvas.boundingBox();
  const touchSession = await context.newCDPSession(page);
  const points = [[30, 80], [80, 25], [135, 135], [230, 90]];
  for (let i = 0; i < points.length; i++) {
    await touchSession.send('Input.dispatchTouchEvent', {type: i === 0 ? 'touchStart' : 'touchMove', touchPoints: [{x: touchBox.x + points[i][0], y: touchBox.y + points[i][1], id: 1}]});
  }
  await touchSession.send('Input.dispatchTouchEvent', {type: 'touchEnd', touchPoints: []});
  await touchSession.detach();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= 390), true);
  await page.screenshot({path: path.join(output, 'mobile-conferencia.png'), fullPage: true});
  await page.getByRole('button', {name: 'Assinar e finalizar OS'}).click();
  await page.waitForURL(`**/ordens/${fixture.ordem}/`);
  assert.equal(await page.locator('.os-signature').count(), 1);
  assert.equal(await page.getByRole('link', {name: 'Editar atendimento'}).count(), 0);
  const pdfPath = await page.getByRole('link', {name: 'Gerar PDF da OS'}).getAttribute('href');
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('link', {name: 'Gerar PDF da OS'}).click()]);
  await download.saveAs(path.join(output, 'os-validation.pdf'));
  assert.equal(fs.readFileSync(path.join(output, 'os-validation.pdf')).subarray(0, 5).toString(), '%PDF-');
  await page.screenshot({path: path.join(output, 'mobile-finalizada.png'), fullPage: true});
  await page.setViewportSize({width: 1365, height: 900});
  await page.screenshot({path: path.join(output, 'desktop-finalizada.png'), fullPage: true});
  await page.getByRole('link', {name: 'Voltar para VERTYX'}).click();
  await page.waitForURL('**/vertyx/');
  assert.equal(await page.getByRole('heading', {name: 'VERTYX', exact: true}).count(), 1);
  fs.writeFileSync(path.join(output, 'browser-result.json'), JSON.stringify({ordem: fixture.ordem, organization: fixture.organization, pdf_path: pdfPath, cookies: await context.cookies()}));
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: Home VERTYX; entrada e retorno ao ERP; início com GPS simulado; foto; edição; GPS negado; conferência; limpar; bloquear assinatura vazia; refazer assinatura; finalizar; PDF; layout mobile sem overflow; desktop; nenhum erro JavaScript.');
})().catch(error => { console.error(error); process.exit(1); });
